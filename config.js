/* تحويل الأرقام المعروضة إلى الأرقام اللاتينية (يعمل على كل النصوص الثابتة والمتولّدة) */
(function () {
  if (typeof document === "undefined" || window.SURVEY_CONFIG.DIGITS !== "latin") return;
  var MAP = { "٠":"0","١":"1","٢":"2","٣":"3","٤":"4","٥":"5","٦":"6","٧":"7","٨":"8","٩":"9","٫":".","٪":"%" };
  var RE = /[٠-٩٫٪]/g;
  function conv(node) {
    if (node.nodeType === 3) {
      var t = node.nodeValue;
      if (RE.test(t)) { RE.lastIndex = 0; node.nodeValue = t.replace(RE, function (c) { return MAP[c]; }); }
      RE.lastIndex = 0;
    } else if (node.nodeType === 1 && node.tagName !== "SCRIPT" && node.tagName !== "STYLE" && node.tagName !== "TEXTAREA") {
      for (var c = node.firstChild; c; c = c.nextSibling) conv(c);
    }
  }
  function start() {
    conv(document.body);
    new MutationObserver(function (ms) {
      ms.forEach(function (m) {
        if (m.type === "characterData") conv(m.target);
        else m.addedNodes.forEach(conv);
      });
    }).observe(document.body, { childList: true, subtree: true, characterData: true });
    document.title = document.title.replace(RE, function (c) { return MAP[c]; });
  }
  if (document.body) start(); else document.addEventListener("DOMContentLoaded", start);
})();